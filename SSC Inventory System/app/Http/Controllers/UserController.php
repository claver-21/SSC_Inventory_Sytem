<?php

namespace App\Http\Controllers;

use App\Models\Permission;
use App\Models\Role;
use App\Models\User;
use App\Rules\StrongPassword;
use App\Services\AuditLogService;
use App\Services\SettingsService;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Str;
use Illuminate\Validation\Rule;
use Illuminate\View\View;
use Symfony\Component\HttpFoundation\StreamedResponse;

class UserController extends Controller
{
    public const SSC_POSITIONS = [
        'SSC President',
        'SSC Vice President',
        'SSC Secretary',
        'SSC Treasurer',
        'SSC Auditor',
        'SSC P.R.O.',
        'SSC Senator',
        'Year Representative',
        'SSC Member',
        'System Administrator',
    ];

    public function __construct(
        protected AuditLogService $auditLog,
        protected SettingsService $settings
    ) {
    }

    public function index(Request $request): View
    {
        $query = User::query()->with('role');

        if ($search = trim((string) $request->input('search'))) {
            $query->where(function ($q) use ($search): void {
                $q->where('name', 'like', "%{$search}%")
                    ->orWhere('email', 'like', "%{$search}%")
                    ->orWhere('school_id', 'like', "%{$search}%")
                    ->orWhere('position', 'like', "%{$search}%");
            });
        }

        if ($roleId = $request->input('role_id')) {
            $query->where('role_id', $roleId);
        }

        return view('users.index', [
            'users' => $query->orderBy('name')->paginate(15)->withQueryString(),
            'roles' => Role::with('permissions')->orderBy('id')->get(),
            'permissionsByModule' => Permission::orderBy('module')->orderBy('id')->get()->groupBy('module'),
            'activeTab' => $request->input('tab', 'users'),
            'allowedDomain' => $this->allowedEmailDomain(),
            'positions' => self::SSC_POSITIONS,
        ]);
    }

    public function create(): View
    {
        return view('users.create', [
            'roles' => Role::orderBy('id')->get(),
            'allowedDomain' => $this->allowedEmailDomain(),
            'positions' => self::SSC_POSITIONS,
        ]);
    }

    public function store(Request $request): RedirectResponse
    {
        $domain = $this->allowedEmailDomain();
        $fullName = trim((string) ($request->input('name') ?: trim($request->input('first_name', '') . ' ' . $request->input('last_name', ''))));
        $request->merge(['name' => $fullName]);

        $passwordRules = ['nullable'];
        if ($request->filled('password')) {
            $passwordRules = ['string', new StrongPassword()];
            if ($request->has('password_confirmation')) {
                $passwordRules[] = 'confirmed';
            }
        }

        $validated = $request->validate([
            'name' => ['required', 'string', 'max:150'],
            'email' => [
                'required',
                'email',
                'max:150',
                Rule::unique('users', 'email'),
                function (string $attribute, mixed $value, \Closure $fail) use ($domain): void {
                    $email = Str::lower(trim((string) $value));
                    if (! Str::endsWith($email, '@' . $domain)) {
                        $fail("Only authorized PCB SSC institutional emails (@{$domain}) may be created.");
                    }
                },
            ],
            'role_id' => ['required', 'exists:roles,id'],
            'password' => $passwordRules,
            'school_id' => ['nullable', 'string', 'max:50'],
            'sex' => ['nullable', Rule::in(['Male', 'Female'])],
            'position' => ['nullable', 'string', 'max:100'],
            'department' => ['nullable', 'string', 'max:120'],
            'phone' => ['nullable', 'string', 'max:40'],
            'is_active' => ['sometimes', 'boolean'],
        ]);

        $autoGeneratedPassword = null;
        $rawPassword = trim((string) ($validated['password'] ?? ''));
        if ($rawPassword === '') {
            $autoGeneratedPassword = $this->generateDefaultPassword($fullName, $validated['school_id'] ?? null);
            $rawPassword = $autoGeneratedPassword;
        }

        $created = User::create([
            'role_id' => $validated['role_id'],
            'name' => $fullName,
            'email' => Str::lower(trim($validated['email'])),
            'password' => Hash::make($rawPassword),
            'school_id' => $validated['school_id'] ?? null,
            'sex' => $validated['sex'] ?? null,
            'position' => $validated['position'] ?? null,
            'department' => $validated['department'] ?? 'Supreme Student Council',
            'phone' => $validated['phone'] ?? null,
            'is_active' => $request->boolean('is_active', true),
            'privacy_consent_at' => now(),
            'privacy_consent_version' => 'v1.0',
        ]);

        $this->auditLog->log(
            action: 'USER_CREATED',
            module: 'users',
            auditable: $created,
            newValues: $created->only(['name', 'email', 'role_id', 'school_id', 'sex', 'position', 'is_active']),
            description: "Created user account {$created->name} ({$created->email}).",
            recordLabel: $created->email,
            actor: $request->user()
        );

        $message = "User account for {$created->name} created successfully.";
        if ($autoGeneratedPassword !== null) {
            $message .= " Initial password: {$autoGeneratedPassword}";
        }

        return redirect()
            ->route('users.index')
            ->with('success', $message);
    }

    public function edit(User $user): View
    {
        return view('users.edit', [
            'userRecord' => $user->load('role'),
            'roles' => Role::orderBy('id')->get(),
            'allowedDomain' => $this->allowedEmailDomain(),
            'positions' => self::SSC_POSITIONS,
        ]);
    }

    public function update(Request $request, User $user): RedirectResponse
    {
        $validated = $request->validate([
            'name' => ['required', 'string', 'max:150'],
            'email' => ['required', 'email', 'max:150', Rule::unique('users', 'email')->ignore($user->id)],
            'role_id' => ['required', 'exists:roles,id'],
            'password' => ['nullable', 'confirmed', new StrongPassword()],
            'school_id' => ['nullable', 'string', 'max:50'],
            'sex' => ['nullable', Rule::in(['Male', 'Female'])],
            'position' => ['nullable', 'string', 'max:100'],
            'department' => ['nullable', 'string', 'max:120'],
            'phone' => ['nullable', 'string', 'max:40'],
            'is_active' => ['sometimes', 'boolean'],
        ]);

        $isActive = $request->boolean('is_active');
        if ($user->id === $request->user()->id && ! $isActive) {
            return back()->with('error', 'You cannot deactivate your own administrator account.');
        }

        $old = $user->only(['name', 'email', 'role_id', 'school_id', 'sex', 'position', 'department', 'phone', 'is_active']);

        $data = [
            'name' => $validated['name'],
            'email' => Str::lower(trim($validated['email'])),
            'role_id' => $validated['role_id'],
            'school_id' => $validated['school_id'] ?? null,
            'sex' => $validated['sex'] ?? null,
            'position' => $validated['position'] ?? null,
            'department' => $validated['department'] ?? null,
            'phone' => $request->exists('phone') ? ($validated['phone'] ?? null) : $user->phone,
            'is_active' => $isActive,
        ];

        if (! empty($validated['password'])) {
            $data['password'] = Hash::make($validated['password']);
        }

        $user->update($data);

        $this->auditLog->log(
            action: 'USER_UPDATED',
            module: 'users',
            auditable: $user,
            oldValues: $old,
            newValues: $user->only(['name', 'email', 'role_id', 'school_id', 'sex', 'position', 'department', 'phone', 'is_active']),
            description: "Updated user account {$user->name} ({$user->email}).",
            recordLabel: $user->email,
            actor: $request->user()
        );

        return redirect()
            ->route('users.index')
            ->with('success', "User account {$user->name} updated.");
    }

    public function toggleStatus(Request $request, User $user): RedirectResponse
    {
        if ($user->id === $request->user()->id) {
            return back()->with('error', 'You cannot deactivate your own active session.');
        }

        $oldStatus = $user->is_active;
        $user->update(['is_active' => ! $oldStatus]);

        $this->auditLog->log(
            action: 'USER_STATUS_TOGGLED',
            module: 'users',
            auditable: $user,
            oldValues: ['is_active' => $oldStatus],
            newValues: ['is_active' => $user->is_active],
            description: ($user->is_active ? 'Activated' : 'Deactivated') . " user {$user->email}.",
            recordLabel: $user->email,
            actor: $request->user()
        );

        return back()->with('success', "User {$user->name} is now " . ($user->is_active ? 'active' : 'inactive') . '.');
    }

    public function unlock(Request $request, User $user): RedirectResponse
    {
        $user->forceFill([
            'failed_login_attempts' => 0,
            'locked_until' => null,
        ])->save();

        $this->auditLog->log(
            action: 'ACCOUNT_UNLOCKED',
            module: 'security',
            auditable: $user,
            description: "Unlocked account {$user->email} and cleared failed login attempts.",
            recordLabel: $user->email,
            actor: $request->user()
        );

        return back()->with('success', "Account {$user->name} has been unlocked.");
    }

    public function updateRolePermissions(Request $request, Role $role): RedirectResponse
    {
        $validated = $request->validate([
            'permissions' => ['nullable', 'array'],
            'permissions.*' => ['exists:permissions,id'],
        ]);

        $permissionIds = $validated['permissions'] ?? [];

        if ($role->slug === Role::SLUG_ADMIN) {
            $protectedIds = Permission::whereIn('slug', ['users.manage', 'settings.manage', 'audit_logs.view', 'dashboard.view'])
                ->pluck('id')
                ->all();
            $permissionIds = array_values(array_unique(array_merge($permissionIds, $protectedIds)));
        }

        $oldSlugs = $role->permissions()->pluck('slug')->all();
        $role->permissions()->sync($permissionIds);
        $newSlugs = $role->permissions()->pluck('slug')->all();

        $this->auditLog->log(
            action: 'ROLE_PERMISSIONS_UPDATED',
            module: 'users',
            auditable: $role,
            oldValues: ['permissions' => $oldSlugs],
            newValues: ['permissions' => $newSlugs],
            description: "Updated permissions matrix for role {$role->name}.",
            recordLabel: $role->slug,
            actor: $request->user()
        );

        return redirect()
            ->route('users.index', ['tab' => 'roles'])
            ->with('success', "Permissions updated for role {$role->name}.");
    }

    public function destroy(Request $request, User $user): RedirectResponse
    {
        if ($user->id === $request->user()->id) {
            return back()->with('error', 'You cannot remove your own administrator account.');
        }

        $email = $user->email;
        $name = $user->name;
        $user->delete();

        $this->auditLog->log(
            action: 'USER_REMOVED',
            module: 'users',
            auditable: $user,
            description: "Removed user account {$name} ({$email}).",
            recordLabel: $email,
            actor: $request->user()
        );

        return redirect()
            ->route('users.index')
            ->with('success', "User account {$name} has been removed.");
    }

    public function bulkTemplate(): StreamedResponse
    {
        $domain = $this->allowedEmailDomain();

        return response()->streamDownload(function () use ($domain): void {
            $out = fopen('php://output', 'w');
            fputcsv($out, ['first_name', 'last_name', 'email', 'school_id', 'sex', 'role', 'position', 'password']);
            fputcsv($out, ['Juan', 'Dela Cruz', "juandelacruz@{$domain}", '24-12345', 'Male', 'SSC Student', 'SSC Secretary', '']);
            fclose($out);
        }, 'ssc_accounts_template.csv', [
            'Content-Type' => 'text/csv; charset=UTF-8',
        ]);
    }

    public function bulkImport(Request $request): RedirectResponse
    {
        $request->validate([
            'csv_file' => ['required', 'file', 'mimes:csv,txt', 'max:2048'],
        ]);

        $domain = $this->allowedEmailDomain();
        $rolesBySlug = Role::all()->keyBy('slug');
        $defaultRole = $rolesBySlug->get(Role::SLUG_MEMBER) ?? Role::firstOrFail();

        $handle = fopen($request->file('csv_file')->getRealPath(), 'r');
        if (! $handle) {
            return back()->with('error', 'Unable to read the uploaded CSV file.');
        }

        $headers = null;
        $created = 0;
        $skipped = 0;

        while (($row = fgetcsv($handle)) !== false) {
            if ($row === [null] || count(array_filter($row, fn ($v) => trim((string) $v) !== '')) === 0) {
                continue;
            }

            if ($headers === null) {
                $normalized = array_map(fn ($v) => Str::snake(strtolower(trim((string) $v))), $row);
                if (in_array('email', $normalized, true) || in_array('first_name', $normalized, true)) {
                    $headers = $normalized;
                    continue;
                }
                $headers = ['first_name', 'last_name', 'email', 'school_id', 'sex', 'role', 'position', 'password'];
            }

            $assoc = [];
            foreach ($headers as $idx => $key) {
                $assoc[$key] = trim((string) ($row[$idx] ?? ''));
            }

            $firstName = $assoc['first_name'] ?? '';
            $lastName = $assoc['last_name'] ?? '';
            $fullName = trim(($assoc['name'] ?? '') ?: "{$firstName} {$lastName}");
            if ($fullName === '') {
                $skipped++;
                continue;
            }

            $email = Str::lower($assoc['email'] ?? '');
            if ($email === '') {
                $slugName = preg_replace('/[^a-z0-9]/', '', Str::lower($fullName));
                $email = ($slugName ?: 'student') . '@' . $domain;
            }

            if (! Str::endsWith($email, '@' . $domain) || User::withTrashed()->where('email', $email)->exists()) {
                $skipped++;
                continue;
            }

            $schoolId = ($assoc['school_id'] ?? '') !== '' ? $assoc['school_id'] : null;
            $rawSex = strtolower($assoc['sex'] ?? '');
            $sex = str_starts_with($rawSex, 'm') ? 'Male' : (str_starts_with($rawSex, 'f') ? 'Female' : null);

            $rawRole = strtolower($assoc['role'] ?? '');
            $role = str_contains($rawRole, 'admin')
                ? ($rolesBySlug->get(Role::SLUG_ADMIN) ?? $defaultRole)
                : $defaultRole;

            $rawPassword = $assoc['password'] ?? '';
            $password = $rawPassword !== '' ? $rawPassword : $this->generateDefaultPassword($fullName, $schoolId);

            User::create([
                'role_id' => $role->id,
                'name' => $fullName,
                'email' => $email,
                'password' => Hash::make($password),
                'school_id' => $schoolId,
                'sex' => $sex,
                'position' => ($assoc['position'] ?? '') !== '' ? $assoc['position'] : 'SSC Member',
                'department' => 'Supreme Student Council',
                'is_active' => true,
                'privacy_consent_at' => now(),
                'privacy_consent_version' => 'v1.0',
            ]);

            $created++;
        }

        fclose($handle);

        $this->auditLog->log(
            action: 'USERS_BULK_IMPORTED',
            module: 'users',
            newValues: ['created' => $created, 'skipped' => $skipped],
            description: "Bulk imported {$created} SSC user account(s) ({$skipped} skipped).",
            recordLabel: 'bulk_csv',
            actor: $request->user()
        );

        return redirect()
            ->route('users.index')
            ->with('success', "Bulk import finished: {$created} account(s) created" . ($skipped > 0 ? ", {$skipped} skipped." : '.'));
    }

    private function allowedEmailDomain(): string
    {
        return Str::lower(ltrim((string) $this->settings->get('allowed_email_domain', 'pcb-ssc.edu.ph'), '@'));
    }

    private function generateDefaultPassword(string $fullName, ?string $schoolId): string
    {
        $letters = preg_replace('/[^a-zA-Z]/', '', Str::ascii($fullName));
        $base = $letters !== '' ? ucfirst(strtolower($letters)) : 'Pcbstudent';

        $idText = trim((string) $schoolId);
        $afterDash = str_contains($idText, '-') ? Str::afterLast($idText, '-') : $idText;
        $digits = preg_replace('/\D/', '', $afterDash);
        if ($digits === '') {
            $digits = preg_replace('/\D/', '', $idText);
        }
        if ($digits === '') {
            $digits = '2026';
        }

        $candidate = $base . $digits;
        if (! preg_match('/\d/', $candidate)) {
            $candidate .= '2026';
        }
        while (strlen($candidate) < 12) {
            $candidate .= '2026';
        }

        return $candidate;
    }
