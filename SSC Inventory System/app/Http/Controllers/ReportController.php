<?php

namespace App\Http\Controllers;

use App\Models\InventoryCategory;
use App\Models\InventoryCondition;
use App\Models\InventoryItem;
use App\Models\InventoryLocation;
use App\Models\User;
use App\Services\AuditLogService;
use App\Services\ReportService;
use Barryvdh\DomPDF\Facade\Pdf;
use Illuminate\Http\Request;
use Illuminate\Http\Response;
use Illuminate\View\View;
use Shuchkin\SimpleXLSXGen;
use Symfony\Component\HttpFoundation\StreamedResponse;

class ReportController extends Controller
{
    public function __construct(
        protected ReportService $reportService,
        protected AuditLogService $auditLog
    ) {
    }

    public function index(Request $request): View
    {
        return view('reports.index', [
            'reports' => $this->reportService->availableReportsFor($request->user()),
        ]);
    }

    public function show(Request $request, string $type): View
    {
        $user = $request->user();
        if (! $this->reportService->canAccess($user, $type)) {
            abort(403, 'You are not authorized to access this report.');
        }

        $filters = $this->extractFilters($request);
        $report = $this->reportService->build($type, $filters, $user);
        $meta = $this->reportService->institutionalMeta($user);

        return view('reports.show', [
            'type' => $type,
            'report' => $report,
            'meta' => $meta,
            'filters' => $filters,
            'categories' => InventoryCategory::orderBy('name')->get(['id', 'name']),
            'locations' => InventoryLocation::orderBy('name')->get(['id', 'name']),
            'conditions' => InventoryCondition::orderBy('severity_rank')->get(['id', 'name']),
            'statuses' => InventoryItem::STATUSES,
            'users' => User::orderBy('name')->get(['id', 'name']),
        ]);
    }

    public function exportPdf(Request $request, string $type): Response
    {
        $user = $request->user();
        if (! $this->reportService->canAccess($user, $type)) {
            abort(403);
        }

        $filters = $this->extractFilters($request);
        $report = $this->reportService->build($type, $filters, $user);
        $meta = $this->reportService->institutionalMeta($user);

        $logoDataUri = null;
        $jpgPath = public_path('images/pcb-ssc-logo.jpg');
        if (is_file($jpgPath)) {
            $logoDataUri = 'data:image/jpeg;base64,' . base64_encode((string) file_get_contents($jpgPath));
        }

        $this->auditLog->log(
            action: 'report.exported_pdf',
            module: 'reports',
            description: "Exported PDF report: {$report['title']}.",
            recordLabel: $type,
            actor: $user
        );

        $pdf = Pdf::loadView('reports.pdf', [
            'report' => $report,
            'meta' => $meta,
            'logoDataUri' => $logoDataUri,
        ])->setPaper('a4', 'landscape');

        $filename = 'pcb_ssc_' . $type . '_' . now()->format('Ymd_His') . '.pdf';

        return $pdf->download($filename);
    }

    public function exportExcel(Request $request, string $type): Response
    {
        $user = $request->user();
        if (! $this->reportService->canAccess($user, $type)) {
            abort(403);
        }

        $filters = $this->extractFilters($request);
        $report = $this->reportService->build($type, $filters, $user);
        $meta = $this->reportService->institutionalMeta($user);

        $colCount = max(4, count($report['columns']));
        $lastCol = SimpleXLSXGen::coord2cell($colCount - 1);

        $rows = [];
        $rows[] = ['<style bgcolor="#650D1B" color="#FFFFFF" font-size="14"><center><b>' . htmlspecialchars($meta['institution_name'], ENT_XML1) . '</b></center></style>'];
        $rows[] = ['<style bgcolor="#841B2D" color="#FFFFFF" font-size="11"><center><b>' . htmlspecialchars($meta['organization_name'] . ' — ' . $report['title'], ENT_XML1) . '</b></center></style>'];
        $rows[] = ["\0Generated On: " . $meta['generated_at'], "\0Generated By: " . $meta['generated_by']];
        $rows[] = [];

        $headerRow = [];
        foreach ($report['columns'] as $col) {
            $headerRow[] = '<style bgcolor="#650D1B" color="#FFFFFF" border="thin"><b>' . htmlspecialchars((string) $col, ENT_XML1) . '</b></style>';
        }
        $rows[] = $headerRow;

        foreach ($report['rows'] as $row) {
            $safeRow = [];
            foreach ($row as $cell) {
                if (is_int($cell) || is_float($cell)) {
                    $safeRow[] = $cell;
                } else {
                    $safeRow[] = "\0" . $this->reportService->sanitizeSpreadsheetCell($cell);
                }
            }
            $rows[] = $safeRow;
        }

        if (! empty($report['summary'])) {
            $rows[] = [];
            foreach ($report['summary'] as $label => $val) {
                $rows[] = ['<b>' . htmlspecialchars((string) $label, ENT_XML1) . '</b>', "\0" . $this->reportService->sanitizeSpreadsheetCell($val)];
            }
        }

        $xlsx = SimpleXLSXGen::fromArray($rows, substr($report['title'], 0, 31));
        $xlsx->mergeCells("A1:{$lastCol}1");
        $xlsx->mergeCells("A2:{$lastCol}2");

        for ($c = 1; $c <= $colCount; $c++) {
            $xlsx->setColWidth($c, 22);
        }

        $this->auditLog->log(
            action: 'report.exported_excel',
            module: 'reports',
            description: "Exported Excel (.xlsx) report: {$report['title']}.",
            recordLabel: $type,
            actor: $user
        );

        $binary = (string) $xlsx;
        $filename = 'pcb_ssc_' . $type . '_' . now()->format('Ymd_His') . '.xlsx';

        return response($binary, 200, [
            'Content-Type' => 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
            'Content-Disposition' => 'attachment; filename="' . $filename . '"',
            'Content-Length' => (string) strlen($binary),
        ]);
    }

    public function exportCsv(Request $request, string $type): StreamedResponse
    {
        $user = $request->user();
        if (! $this->reportService->canAccess($user, $type)) {
            abort(403);
        }

        $filters = $this->extractFilters($request);
        $report = $this->reportService->build($type, $filters, $user);
        $meta = $this->reportService->institutionalMeta($user);

        $this->auditLog->log(
            action: 'report.exported_csv',
            module: 'reports',
            description: "Exported CSV report: {$report['title']}.",
            recordLabel: $type,
            actor: $user
        );

        $filename = 'pcb_ssc_' . $type . '_' . now()->format('Ymd_His') . '.csv';

        return response()->streamDownload(function () use ($report, $meta): void {
            $out = fopen('php://output', 'w');
            fwrite($out, "\xEF\xBB\xBF");
            fputcsv($out, [$meta['institution_name']]);
            fputcsv($out, [$meta['organization_name']]);
            fputcsv($out, [$report['title']]);
            fputcsv($out, ['Generated On', $meta['generated_at'], 'Generated By', $meta['generated_by']]);
            fputcsv($out, []);
            fputcsv($out, $report['columns']);

            foreach ($report['rows'] as $row) {
                $safe = array_map(fn ($c) => $this->reportService->sanitizeSpreadsheetCell($c), $row);
                fputcsv($out, $safe);
            }

            if (! empty($report['summary'])) {
                fputcsv($out, []);
                foreach ($report['summary'] as $label => $val) {
                    fputcsv($out, [$label, $this->reportService->sanitizeSpreadsheetCell($val)]);
                }
            }

            fclose($out);
        }, $filename, [
            'Content-Type' => 'text/csv; charset=UTF-8',
        ]);
    }

    protected function extractFilters(Request $request): array
    {
        return $request->only([
            'date_from',
            'date_to',
            'category_id',
            'location_id',
            'status',
            'condition_id',
            'responsible_user_id',
        ]);
    }
}
